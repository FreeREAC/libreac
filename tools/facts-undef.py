"""Write tests/facts/reac_facts_undef.h from reac-protocol's generated reac_facts.h.

    facts-undef.py reac_facts.h OUT

libreac's public headers still define about fifty of the generated names by hand, some
spelled differently (0xC2 vs 0xc2). tests/reac_test_facts.h includes those headers first,
then OUT (which clears every generated name), then reac_facts.h, so a test compiles against
the generated value and no redefinition is diagnosed. OUT is derived from the header by name,
so it cannot fall behind it.
"""
import pathlib
import re
import sys

DEFINE = re.compile(r"^#define REAC_([A-Z0-9_]+)\s+(\S.*?)\s*(?:/\*.*)?$", re.M)


def emit_undef(facts_text):
    lines = ["// SPDX-License-Identifier: GPL-3.0-or-later",
             "// Copyright (C) 2026 Pau Aliagas <linuxnow@gmail.com>",
             "//",
             "// GENERATED by tools/facts-undef.py from reac_facts.h - DO NOT EDIT.",
             "// Clears libreac's hand copies of these names before reac_facts.h",
             "// defines them (see tests/reac_test_facts.h).",
             "#ifndef REAC_TEST_FACTS_UNDEF_H", "#define REAC_TEST_FACTS_UNDEF_H"]
    lines += [f"#undef REAC_{m.group(1)}" for m in DEFINE.finditer(facts_text)]
    lines += ["#endif", ""]
    return "\n".join(lines)


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2
    pathlib.Path(argv[2]).write_text(emit_undef(pathlib.Path(argv[1]).read_text()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
