# usage: ci-grammar-parser.sh <reac-protocol checkout>
#
# Generates spec/reac.py in that checkout from spec/reac.ksy, so python/test_libreac.py's grammar arm
# (python/libreac/ksy.py) RUNS instead of skipping. The parser is generated, never committed, and
# kaitai-struct-compiler is in no distro repository: this fetches the 0.11 release zip, the same
# artefact reac-protocol's own ksy-conformance job uses, and holds it to a pinned checksum. It needs
# java, curl and unzip at build time only. The Python runtime (pip install kaitaistruct==0.11, the
# version the generated code asks for) is the caller's step.
set -eu
proto=${1:?usage: ci-grammar-parser.sh <reac-protocol checkout>}
ksy=$proto/spec/reac.ksy
[ -f "$ksy" ] || { echo "ci-grammar-parser: no $ksy" >&2; exit 2; }
ver=0.11
sha=ff89389d9dc9e770d78a24af328763cb1f8e7b31ce7766c9edf10669a060f2a2
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
curl -fsSL -o "$tmp/ksc.zip" "https://github.com/kaitai-io/kaitai_struct_compiler/releases/download/$ver/kaitai-struct-compiler-$ver.zip"
echo "$sha  $tmp/ksc.zip" | sha256sum -c - >/dev/null || { echo "ci-grammar-parser: the compiler zip does not match its pinned checksum" >&2; exit 1; }
unzip -q "$tmp/ksc.zip" -d "$tmp"
"$tmp/kaitai-struct-compiler-$ver/bin/kaitai-struct-compiler" -t python --outdir "$proto/spec" "$ksy"
[ -f "$proto/spec/reac.py" ] || { echo "ci-grammar-parser: the compiler wrote no reac.py" >&2; exit 1; }
echo "ci-grammar-parser: $proto/spec/reac.py generated by kaitai-struct-compiler $ver"
